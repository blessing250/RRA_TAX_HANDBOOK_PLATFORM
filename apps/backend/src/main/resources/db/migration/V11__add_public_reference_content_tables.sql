create table articles (
    id bigint generated by default as identity primary key,
    slug varchar(255) not null unique,
    status varchar(50) not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table article_translations (
    id bigint generated by default as identity primary key,
    article_id bigint not null,
    language varchar(20) not null,
    title varchar(255) not null,
    summary varchar(2000),
    content varchar(12000),
    constraint fk_article_translations_article foreign key (article_id) references articles (id),
    constraint uq_article_translation_article_language unique (article_id, language)
);

create table categories (
    id bigint generated by default as identity primary key,
    slug varchar(255) not null unique
);

create table category_translations (
    id bigint generated by default as identity primary key,
    category_id bigint not null,
    language varchar(20) not null,
    name varchar(255) not null,
    constraint fk_category_translations_category foreign key (category_id) references categories (id),
    constraint uq_category_translation_category_language unique (category_id, language)
);

create table faqs (
    id bigint generated by default as identity primary key,
    slug varchar(255) not null unique
);

create table faq_translations (
    id bigint generated by default as identity primary key,
    faq_id bigint not null,
    language varchar(20) not null,
    question varchar(255) not null,
    answer varchar(4000) not null,
    constraint fk_faq_translations_faq foreign key (faq_id) references faqs (id),
    constraint uq_faq_translation_faq_language unique (faq_id, language)
);

create table documents (
    id bigint generated by default as identity primary key,
    title varchar(255) not null,
    file_name varchar(255) not null,
    file_url varchar(1000) not null,
    created_at timestamp with time zone not null
);
